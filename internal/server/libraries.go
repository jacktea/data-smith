func (s *Server) handleCreateLibrary(w http.ResponseWriter, r *http.Request) {
	var req libraryRequest
	if err := decodeJSON(r, &req); err != nil {
		writeError(w, http.StatusBadRequest, "%s", err.Error())
		return
	}
	if strings.TrimSpace(req.Name) == "" {
		writeError(w, http.StatusBadRequest, "脚本库名称不能为空")
		return
	}
	lib := &LibraryMeta{
		ID:        newID("lib"),
		Name:      req.Name,
		CreatedAt: time.Now(),
		Versions:  map[string]VersionMeta{},
	}
	if err := os.MkdirAll(s.libraryDirUnchecked(lib.ID), 0o755); err != nil {
		writeError(w, http.StatusInternalServerError, "创建脚本库目录失败: %v", err)
		return
	}
	if err := s.store.PutLibrary(lib); err != nil {
		respondStoreErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, lib)
}

func (s *Server) handleDeleteLibrary(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	unlock := s.lockLibrary(id)
	defer unlock()
	found, err := s.store.DeleteLibrary(id)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	if !found {
		writeError(w, http.StatusNotFound, "脚本库不存在")
		return
	}
	// 连带删除脚本目录。
	_ = os.RemoveAll(s.libraryDirUnchecked(id))
	writeJSON(w, http.StatusOK, map[string]any{"ok": true})
}

// libraryDirUnchecked joins the library scripts directory without existence
// checks (callers validate beforehand).
func (s *Server) libraryDirUnchecked(libID string) string {
	return filepath.Join(s.dataDir, "libraries", libID)
}

// libraryDir resolves and validates the scripts directory of an existing
// library.
func (s *Server) libraryDir(libID string) (string, error) {
	if _, ok := s.store.GetLibrary(libID); !ok {
		return "", errBad("脚本库不存在")
	}
	return s.libraryDirUnchecked(libID), nil
}


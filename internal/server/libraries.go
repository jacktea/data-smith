type registerVersionRequest struct {
	SourceJobID          string `json:"sourceJobId"`
	CompanionJobID       string `json:"companionJobId"`
	IncludeSchema        bool   `json:"includeSchema"`
	IncludeData          bool   `json:"includeData"`
	Version              string `json:"version"`
	Title                string `json:"title"`
	ExpectedConnectionID string `json:"expectedConnectionId"`
}

func (s *Server) handleRegisterVersion(w http.ResponseWriter, r *http.Request) {
	libID := r.PathValue("id")
	if s.beforeLibraryMutation != nil {
		s.beforeLibraryMutation(libID, "register-version")
	}
	unlock := s.lockLibrary(libID)
	defer unlock()
	dir, err := s.libraryDir(libID)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	var req registerVersionRequest
	if err := decodeJSON(r, &req); err != nil {
		writeError(w, http.StatusBadRequest, "%s", err.Error())
		return
	}
	if !req.IncludeSchema && !req.IncludeData {
		writeError(w, http.StatusBadRequest, "includeSchema 与 includeData 至少选择一项")
		return
	}
	version, err := normalizeRegistrationVersion(req.Version)
	if err != nil {
		writeError(w, http.StatusBadRequest, "%s", err.Error())
		return
	}
	if req.Title == "" || strings.ContainsAny(req.Title, ".") {
		writeError(w, http.StatusBadRequest, "版本标题不能为空且不能包含点号")
		return
	}
	job := s.jobs.Get(req.SourceJobID)
	if job == nil {
		writeError(w, http.StatusBadRequest, "来源任务不存在")
		return
	}
	if job.Type() != JobDiffSchema && job.Type() != JobDiffData && job.Type() != JobDiffFull {
		writeError(w, http.StatusBadRequest, "来源任务类型必须为 diff-schema、diff-data 或 diff-full")
		return
	}
	if job.Status() != jobStatusSucceeded {
		writeError(w, http.StatusBadRequest, "来源任务尚未成功完成")
		return
	}
	// 完全对比任务在单一目录内同时产出结构与数据产物,不允许再挂配套任务。
	var companion *Job
	if req.CompanionJobID != "" {
		if job.Type() == JobDiffFull {
			writeError(w, http.StatusBadRequest, "完全对比任务已包含结构与数据产物,无需配套任务")
			return
		}
		companion = s.jobs.Get(req.CompanionJobID)
		if companion == nil {
			writeError(w, http.StatusBadRequest, "配套任务不存在")
			return
		}
		if companion.ID() == job.ID() {
			writeError(w, http.StatusBadRequest, "配套任务不能与来源任务相同")
			return
		}
		if companion.Status() != jobStatusSucceeded {
			writeError(w, http.StatusBadRequest, "配套任务尚未成功完成")
			return
		}
		if companion.Type() == job.Type() {
			writeError(w, http.StatusBadRequest, "配套任务类型必须与来源任务互补(diff-schema / diff-data)")
			return
		}
	}
	var schemaJob, dataJob *Job
	switch job.Type() {
	case JobDiffSchema:
		schemaJob = job
	case JobDiffData:
		dataJob = job
	default: // JobDiffFull: 结构与数据产物在同一任务目录
		schemaJob = job
		dataJob = job
	}
	if companion != nil {
		if companion.Type() == JobDiffSchema {
			schemaJob = companion
		} else {
			dataJob = companion
		}
	}
	if req.IncludeSchema && schemaJob == nil {
		writeError(w, http.StatusBadRequest, "勾选了结构变更但没有可用的结构比对任务")
		return
	}
	if req.IncludeData && dataJob == nil {
		writeError(w, http.StatusBadRequest, "勾选了数据变更但没有可用的数据比对任务")
		return
	}
	if err := s.checkVersionUnique(dir, version); err != nil {
		respondStoreErr(w, err)
		return
	}

	var schemaForward, schemaRollback, dataForward, dataRollback string
	readFrom := func(from *Job, name string) (string, error) {
		raw, err := os.ReadFile(filepath.Join(from.Dir(), name))
		if err != nil {
			if os.IsNotExist(err) {
				return "", errBad("任务 %s 缺少产物 %s,无法登记", from.ID(), name)
			}
			return "", fmt.Errorf("读取任务产物 %s: %w", name, err)
		}
		return string(raw), nil
	}
	if req.IncludeSchema {
		var err error
		if schemaForward, err = readFrom(schemaJob, difflogic.SchemaDiffForwardFile); err != nil {
			writeError(w, http.StatusBadRequest, "%s", err.Error())
			return
		}
		schemaRollback, _ = readFrom(schemaJob, difflogic.SchemaDiffRollbackFile)
	}
	if req.IncludeData {
		var err error
		if dataForward, err = readFrom(dataJob, difflogic.DataDiffForwardFile); err != nil {
			writeError(w, http.StatusBadRequest, "%s", err.Error())
			return
		}
		dataRollback, _ = readFrom(dataJob, difflogic.DataDiffRollbackFile)
	}

	upContent, downContent := difflogic.AssembleVersionScripts(
		req.IncludeSchema, req.IncludeData,
		schemaForward, schemaRollback, dataForward, dataRollback,
	)

	upFile := fmt.Sprintf("V%s__%s.up.sql", version, req.Title)
	downFile := fmt.Sprintf("V%s__%s.down.sql", version, req.Title)
	if err := os.WriteFile(filepath.Join(dir, upFile), []byte(upContent), 0o644); err != nil {
		writeError(w, http.StatusInternalServerError, "写入 up 脚本失败: %v", err)
		return
	}
	if err := os.WriteFile(filepath.Join(dir, downFile), []byte(downContent), 0o644); err != nil {
		writeError(w, http.StatusInternalServerError, "写入 down 脚本失败: %v", err)
		return
	}
	if err := s.store.SetVersionMeta(libID, version, VersionMeta{ExpectedConnectionID: req.ExpectedConnectionID}); err != nil {
		respondStoreErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"upFile": upFile, "downFile": downFile})
}

// checkVersionUnique rejects a registration version that already exists among
// the library's up scripts (normalized comparison).
func (s *Server) checkVersionUnique(dir, version string) error {
	scripts, err := listScripts(dir)
	if err != nil {
		return err
	}
	for _, script := range scripts {
		if script.Direction == "down" {
			continue
		}
		if normalizedVersion(script.Version) == version {
			return errBad("版本 %s 已存在于脚本库(%s)", version, script.FileName)
		}
	}
	return nil
}

func normalizeRegistrationVersion(version string) (string, error) {
	matches := versionOnlyRe.FindStringSubmatch(strings.TrimSpace(version))
	if matches == nil {
		return "", errBad("版本号须为点分数字(如 1.0.0)")
	}
	return matches[1], nil
}

func normalizedVersion(version string) string {
	return strings.TrimPrefix(strings.ToLower(strings.TrimSpace(version)), "v")
}


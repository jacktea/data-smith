// scriptNameRe mirrors the migration filename grammar in
// internal/datasmith/migrate/local; direction is captured raw so files without
// an explicit .up/.down report "".
var scriptNameRe = regexp.MustCompile(`^([vV]\d+(?:\.\d+)*|\d+)__([^.]+)(?:\.(up|down))?\.(sql|json)$`)

var versionOnlyRe = regexp.MustCompile(`^[vV]?(\d+(?:\.\d+)*)$`)

type scriptInfo struct {
	FileName   string    `json:"fileName"`
	Version    string    `json:"version"`
	Title      string    `json:"title"`
	Direction  string    `json:"direction"`
	Ext        string    `json:"ext"`
	Size       int64     `json:"size"`
	ModifiedAt time.Time `json:"modifiedAt"`
}

func (s scriptInfo) isUp() bool { return s.Direction == "" || s.Direction == "up" }


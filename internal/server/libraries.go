type ledgerRow struct {
	Version       string `json:"version"`
	Title         string `json:"title"`
	Status        string `json:"status"`
	Checksum      string `json:"checksum"`
	AppliedAt     string `json:"appliedAt"`
	ExecutionTime int64  `json:"executionTime"`
	ErrorSummary  string `json:"errorSummary"`
}

type latestAppliedView struct {
	Version   string `json:"version"`
	AppliedAt string `json:"appliedAt"`
}

type pendingMigrationView struct {
	Version string `json:"version"`
	Title   string `json:"title"`
}

type migratePlanView struct {
	LatestApplied *latestAppliedView     `json:"latestApplied"`
	Applied       []ledgerRow            `json:"applied"`
	Pending       []pendingMigrationView `json:"pending"`
	NextVersion   string                 `json:"nextVersion"`
	// Warnings 列出扫描脚本库时被跳过的不合规文件名（不参与迁移链），
	// 前端在推进迁移前展示，避免「迁移缺版本」被静默吞掉。
	Warnings []string `json:"warnings,omitempty"`
}

func (s *Server) handleMigratePlan(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	libID := q.Get("libraryId")
	connectionID := q.Get("connectionId")
	targetVersion := q.Get("targetVersion")
	dir, err := s.libraryDir(libID)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	stored, ok := s.store.GetConnection(connectionID)
	if !ok {
		writeError(w, http.StatusBadRequest, "连接不存在")
		return
	}
	adapter, err := s.openAdapter(r.Context(), stored.ConnConfig())
	if err != nil {
		writeError(w, http.StatusBadRequest, "连接数据库失败: %v", err)
		return
	}
	defer adapter.Close()

	rows, err := readLedger(r.Context(), adapter)
	if err != nil {
		// 老版本建的账本可能缺 checksum 等列:先用引擎的 EnsureVersionTable
		// 幂等自愈表结构,再重试一次读取;正常路径保持只读。
		if healErr := pkgmigrate.EnsureVersionTable(adapter); healErr != nil {
			writeError(w, http.StatusBadRequest, "修复迁移账本失败: %v", healErr)
			return
		}
		rows, err = readLedger(r.Context(), adapter)
	}
	if err != nil {
		writeError(w, http.StatusBadRequest, "读取迁移账本失败: %v", err)
		return
	}
	if rows == nil {
		rows = []ledgerRow{}
	}
	successSet := make(map[string]bool, len(rows))
	latest := (*latestAppliedView)(nil)
	for i := len(rows) - 1; i >= 0; i-- {
		if rows[i].Status == "success" {
			successSet[normalizedVersion(rows[i].Version)] = true
			if latest == nil {
				latest = &latestAppliedView{Version: rows[i].Version, AppliedAt: rows[i].AppliedAt}
			}
		}
	}

	files, skipped, err := local.ScanMigrations(dir)
	if err != nil {
		writeError(w, http.StatusBadRequest, "扫描脚本库失败: %v", err)
		return
	}
	local.SortMigrations(files)
	var warnings []string
	for _, name := range skipped {
		warnings = append(warnings, fmt.Sprintf("跳过不合规迁移文件名(不参与迁移链): %s", name))
	}
	pending := []pendingMigrationView{}
	for _, f := range files {
		if f.Direction != "up" {
			continue
		}
		if targetVersion != "" && local.CompareVersion(f.Version, targetVersion) > 0 {
			continue
		}
		if successSet[normalizedVersion(f.Version)] {
			continue
		}
		pending = append(pending, pendingMigrationView{
			Version: normalizedVersion(f.Version),
			Title:   f.Title,
		})
	}
	writeJSON(w, http.StatusOK, migratePlanView{
		LatestApplied: latest,
		Applied:       rows,
		Pending:       pending,
		NextVersion:   nextLibraryVersion(dir),
		Warnings:      warnings,
	})
}

// readLedger returns all schema_migrations rows ordered by id, or nil when the
// ledger table does not exist yet.
func readLedger(ctx context.Context, adapter conn.DBAdapter) ([]ledgerRow, error) {
	dbType := adapter.GetConfig().Type
	var existsQuery string
	switch dbType {
	case consts.DBTypeMySQL:
		existsQuery = "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = database() AND table_name = 'schema_migrations'"
	case consts.DBTypePostgres:
		existsQuery = "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'schema_migrations'"
	default:
		return nil, fmt.Errorf("不支持的数据库类型: %s", dbType)
	}
	var count int
	if err := adapter.GetConn().QueryRowContext(ctx, existsQuery).Scan(&count); err != nil {
		return nil, err
	}
	if count == 0 {
		return nil, nil
	}
	dbRows, err := adapter.GetConn().QueryContext(ctx,
		"SELECT version, title, checksum, status, applied_at, execution_time, error_summary FROM schema_migrations ORDER BY id")
	if err != nil {
		return nil, err
	}
	defer dbRows.Close()
	out := []ledgerRow{}
	for dbRows.Next() {
		var row ledgerRow
		var title, checksum, errorSummary, appliedAt sqlNullString
		var executionTime sqlNullInt64
		if err := dbRows.Scan(&row.Version, &title, &checksum, &row.Status, &appliedAt, &executionTime, &errorSummary); err != nil {
			return nil, err
		}
		row.Title = title.value()
		row.Checksum = checksum.value()
		row.AppliedAt = appliedAt.value()
		row.ExecutionTime = executionTime.value()
		row.ErrorSummary = errorSummary.value()
		out = append(out, row)
	}
	return out, dbRows.Err()
}

// sqlNullString/sqlNullInt64 are tiny scan targets keeping the ledger read
// tolerant of NULL columns.
type sqlNullString struct {
	set bool
	v   string
}

func (n *sqlNullString) Scan(src any) error {
	n.set = src != nil
	if s, ok := src.(string); ok {
		n.v = s
	} else if b, ok := src.([]byte); ok {
		n.v = string(b)
	} else if t, ok := src.(time.Time); ok {
		n.v = t.Format(time.RFC3339)
	} else if src != nil {
		return errors.New("ledger: 非字符串列")
	}
	return nil
}

func (n *sqlNullString) value() string { return n.v }

type sqlNullInt64 struct {
	set bool
	v   int64
}

func (n *sqlNullInt64) Scan(src any) error {
	n.set = src != nil
	switch value := src.(type) {
	case int64:
		n.v = value
	case []byte:
		parsed, err := strconv.ParseInt(string(value), 10, 64)
		if err != nil {
			return err
		}
		n.v = parsed
	case nil:
	default:
		return errors.New("ledger: 非整数列")
	}
	return nil
}

func (n *sqlNullInt64) value() int64 { return n.v }

// nextLibraryVersion bumps the last numeric segment of the library's maximum
// version; an empty library starts at 1.0.0.
func nextLibraryVersion(dir string) string {
	scripts, err := listScripts(dir)
	if err != nil || len(scripts) == 0 {
		return "1.0.0"
	}
	maxVersion := ""
	for _, script := range scripts {
		normalized := normalizedVersion(script.Version)
		if maxVersion == "" || local.CompareVersion(normalized, maxVersion) > 0 {
			maxVersion = normalized
		}
	}
	if maxVersion == "" {
		return "1.0.0"
	}
	parts := strings.Split(maxVersion, ".")
	last := parts[len(parts)-1]
	number, err := strconv.Atoi(last)
	if err != nil {
		return maxVersion + ".1"
	}
	parts[len(parts)-1] = strconv.Itoa(number + 1)
	return strings.Join(parts, ".")
}

func (s *Server) handleListScripts(w http.ResponseWriter, r *http.Request) {
	libID := r.PathValue("id")
	dir, err := s.libraryDir(libID)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	scripts, err := listScripts(dir)
	if err != nil {
		writeError(w, http.StatusInternalServerError, "读取脚本目录失败: %v", err)
		return
	}
	writeJSON(w, http.StatusOK, scripts)
}

func listScripts(dir string) ([]scriptInfo, error) {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return []scriptInfo{}, nil
	}
	if err != nil {
		return nil, err
	}
	out := []scriptInfo{}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		matches := scriptNameRe.FindStringSubmatch(entry.Name())
		if matches == nil {
			continue
		}
		info, err := entry.Info()
		if err != nil {
			continue
		}
		out = append(out, scriptInfo{
			FileName:   entry.Name(),
			Version:    matches[1],
			Title:      matches[2],
			Direction:  matches[3],
			Ext:        matches[4],
			Size:       info.Size(),
			ModifiedAt: info.ModTime(),
		})
	}
	sort.Slice(out, func(i, k int) bool {
		if cmp := local.CompareVersion(out[i].Version, out[k].Version); cmp != 0 {
			return cmp < 0
		}
		if out[i].Direction != out[k].Direction {
			return out[i].Direction == "" || out[i].Direction == "up" && out[k].Direction == "down"
		}
		return out[i].FileName < out[k].FileName
	})
	return out, nil
}

// parseScriptName validates a client-provided script file name and returns its
// parsed fields. When allowDown is false, down scripts are rejected: they are
// only generated by version registration (read/delete/download still accept
// them so registered versions remain manageable).
func parseScriptName(fileName string, allowDown bool) (*scriptInfo, error) {
	if fileName == "" || fileName != filepath.Base(fileName) || strings.ContainsAny(fileName, `/\`) {
		return nil, errBad("非法的脚本文件名: %s", fileName)
	}
	matches := scriptNameRe.FindStringSubmatch(fileName)
	if matches == nil {
		return nil, errBad("脚本文件名须形如 V1__描述.sql 或 1.2.0__描述.up.sql")
	}
	if matches[3] == "down" && !allowDown {
		return nil, errBad("down 脚本仅能通过版本登记生成")
	}
	if matches[4] == "json" {
		return nil, errBad("仅支持 .sql 脚本(JSON 迁移不受支持)")
	}
	return &scriptInfo{
		FileName:  fileName,
		Version:   matches[1],
		Title:     matches[2],
		Direction: matches[3],
		Ext:       matches[4],
	}, nil
}

type scriptContentRequest struct {
	FileName string `json:"fileName"`
	Content  string `json:"content"`
}

func (s *Server) handleCreateScript(w http.ResponseWriter, r *http.Request) {
	libID := r.PathValue("id")
	unlock := s.lockLibrary(libID)
	defer unlock()
	dir, err := s.libraryDir(libID)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	var req scriptContentRequest
	if err := decodeJSON(r, &req); err != nil {
		writeError(w, http.StatusBadRequest, "%s", err.Error())
		return
	}
	info, err := parseScriptName(req.FileName, false)
	if err != nil {
		respondStoreErr(w, err)
		return
	}
	path := filepath.Join(dir, info.FileName)
	if _, err := os.Stat(path); err == nil {
		writeError(w, http.StatusBadRequest, "脚本 %s 已存在,请使用编辑", info.FileName)
		return
	}
	if err := os.WriteFile(path, []byte(req.Content), 0o644); err != nil {
		writeError(w, http.StatusInternalServerError, "写入脚本失败: %v", err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"fileName": info.FileName, "content": req.Content})
}

